"""Run Tamper Check's static analysis on BugsInPy developer fix commits.

Developer fixes are the control group: they change source and tests together and
are reviewed upstream, so a weakening finding on one is either a real (rare)
weakening of a test by the project itself or a false positive. Every weakening
finding is listed so a person can decide which.

For each bug, the project's GitHub repository is cloned once (blobless partial
clone) under ``--clones-dir``, the fixed commit is checked out, and the working
tree is compared with the buggy commit (``tamper-check --git-base`` semantics).
No Docker, no tests are run, no API calls.

    python scripts/evaluate_tamper_check.py --bugs black:1-5,tqdm:1-3 \
        --output experiment_results/tamper_check_developer_fixes
"""

import argparse
import json
import re
import subprocess
import sys
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT / "src"))

from apr_framework.tamper.changes import changes_from_git
from apr_framework.tamper.models import WEAKENING
from apr_framework.tamper.pipeline import (
    build_report,
    read_test_sources,
    static_findings,
)


def parse_bug_spec(spec: str) -> list[tuple[str, int]]:
    """``black:1-3,tqdm:5`` → [("black", 1), ("black", 2), ("black", 3), ("tqdm", 5)]."""
    bugs: list[tuple[str, int]] = []
    for part in spec.split(","):
        project, _, ids = part.strip().partition(":")
        start, _, end = ids.partition("-")
        for bug_id in range(int(start), int(end or start) + 1):
            bugs.append((project, bug_id))
    return bugs


def read_info(path: Path) -> dict[str, str]:
    return dict(
        re.findall(r'^(\w+)="([^"]*)"', path.read_text(encoding="utf-8"), re.MULTILINE)
    )


def git(repo: Path, *arguments: str) -> str:
    return subprocess.run(
        ["git", "-C", str(repo), *arguments], capture_output=True, text=True, check=True
    ).stdout


def ensure_clone(url: str, destination: Path) -> None:
    if (destination / ".git").is_dir():
        return
    destination.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [
            "git",
            "clone",
            "--quiet",
            "--filter=blob:none",
            "--no-checkout",
            url,
            str(destination),
        ],
        check=True,
    )


def evaluate_bug(bugsinpy: Path, clones: Path, project: str, bug_id: int) -> dict:
    project_info = read_info(bugsinpy / "projects" / project / "project.info")
    bug_info = read_info(
        bugsinpy / "projects" / project / "bugs" / str(bug_id) / "bug.info"
    )
    clone = clones / project
    ensure_clone(project_info["github_url"].rstrip("/") + ".git", clone)
    buggy, fixed = bug_info["buggy_commit_id"], bug_info["fixed_commit_id"]
    git(clone, "checkout", "--quiet", "--force", fixed)
    changes = changes_from_git(clone, buggy)
    findings, classes = static_findings(
        changes, frozenset(), read_test_sources(clone, changes)
    )
    report = build_report(
        {"bug": f"{project}#{bug_id}"}, changes, findings, classes, [], ""
    )
    return {
        "bug": f"{project}#{bug_id}",
        "buggy_commit": buggy,
        "fixed_commit": fixed,
        "verdict": report.verdict,
        "counts": report.counts(),
        "kinds": dict(Counter(finding.kind for finding in report.findings)),
        "changed_files": report.changed_files,
        "weakening": [
            finding.to_json()
            for finding in report.findings
            if finding.severity == WEAKENING
        ],
    }


def write_readme(
    output: Path, results: list[dict], started_at: str, note: str = ""
) -> None:
    verdicts = Counter(result["verdict"] for result in results)
    kinds: Counter = Counter()
    for result in results:
        kinds.update(result["kinds"])
    lines = [
        "# Tamper Check on BugsInPy developer fixes",
        "",
        f"Generated by `scripts/evaluate_tamper_check.py` on {started_at[:10]} (static",
        "analysis only: no Docker, no test runs, no API calls). Each row compares a bug's",
        "buggy commit with its fixed commit, tests included.",
        "",
        *([note, ""] if note else []),
        f"- Bugs: **{len(results)}**",
        f"- Verdicts: {dict(verdicts)}",
        f"- Findings by kind: {dict(sorted(kinds.items()))}",
        "",
        "| Bug | Verdict | weakening / suspicious / strengthening / neutral | Kinds |",
        "|---|---|---|---|",
    ]
    for result in results:
        counts = result["counts"]
        lines.append(
            f"| {result['bug']} | {result['verdict']} | "
            f"{counts['weakening']} / {counts['suspicious']} / {counts['strengthening']} / "
            f"{counts['neutral']} | "
            + ", ".join(
                f"{kind} ×{count}" for kind, count in sorted(result["kinds"].items())
            )
            + " |"
        )
    flagged = [result for result in results if result["weakening"]]
    lines += ["", "## Every weakening finding", ""]
    if not flagged:
        lines.append("None.")
    for result in flagged:
        for finding in result["weakening"]:
            where = finding["file"] + (
                f"::{finding['test']}" if finding["test"] else ""
            )
            lines.append(
                f"- **{result['bug']}** `{finding['kind']}` {where}: {finding['message']}"
            )
            for prefix, text in (("-", finding["before"]), ("+", finding["after"])):
                for text_line in text.splitlines()[:3]:
                    lines.append(f"  `{prefix} {text_line}`")
    (output / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--bugs", required=True, help="e.g. black:1-5,tqdm:1-3")
    parser.add_argument("--bugsinpy", default=str(PROJECT_ROOT / ".tools" / "bugsinpy"))
    parser.add_argument(
        "--clones-dir", default=str(PROJECT_ROOT / ".workspace" / "tamper_check_clones")
    )
    parser.add_argument("--output", required=True)
    parser.add_argument("--note", default="", help="A paragraph for the README")
    args = parser.parse_args()
    started_at = datetime.now(timezone.utc).isoformat()
    output = Path(args.output)
    output.mkdir(parents=True, exist_ok=True)
    results: list[dict] = []
    for project, bug_id in parse_bug_spec(args.bugs):
        try:
            result = evaluate_bug(
                Path(args.bugsinpy), Path(args.clones_dir), project, bug_id
            )
        except (subprocess.CalledProcessError, KeyError, FileNotFoundError) as error:
            result = {
                "bug": f"{project}#{bug_id}",
                "verdict": "error",
                "error": str(error),
                "counts": dict.fromkeys(
                    ("weakening", "suspicious", "strengthening", "neutral"), 0
                ),
                "kinds": {},
                "weakening": [],
            }
        results.append(result)
        print(f"{result['bug']}: {result['verdict']} {result['counts']}", flush=True)
    (output / "results.json").write_text(
        json.dumps(
            {"started_at": started_at, "bugs": args.bugs, "results": results}, indent=2
        )
        + "\n",
        encoding="utf-8",
    )
    write_readme(output, results, started_at, args.note)
    return 0


if __name__ == "__main__":
    sys.exit(main())
