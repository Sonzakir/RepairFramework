import zipfile
from datetime import datetime, timezone
from pathlib import Path

from apr_framework.core.models import EvaluationResult
from apr_framework.reporting.base import ReportGenerator


class ArchiveReportGenerator(ReportGenerator):
    """
    Concrete report generator for dummy evaluation runs.

    It renders a human-readable Markdown summary of the evaluation results into
    the run directory and then bundles the whole run directory (config.json,
    results.json, execution.log, and the generated summary) into a single
    ``<run_name>.zip`` archive placed next to it.
    """

    @property
    def name(self) -> str:
        """
        Stable report generator name used in logs and report metadata.
        """
        return "archive-report-generator"

    def write_summary(self, results: list[EvaluationResult], output_dir: Path) -> Path:
        """
        Write a summary file into ``output_dir`` and archive the run artifacts.

        Args:
            results: Evaluation results produced by the run.
            output_dir: Run directory containing the run artifacts.

        Returns:
            Path to the generated ``.zip`` archive bundling the run artifacts.
        """
        output_dir = Path(output_dir)
        summary_path = output_dir / "report.md"
        summary_path.write_text(self._render_summary(results), encoding="utf-8")

        archive_path = output_dir.parent / f"{output_dir.name}.zip"
        with zipfile.ZipFile(archive_path, "w", zipfile.ZIP_DEFLATED) as archive:
            for artifact in sorted(output_dir.iterdir()):
                if artifact.is_file():
                    archive.write(
                        artifact, arcname=f"{output_dir.name}/{artifact.name}"
                    )

        return archive_path

    def _render_summary(self, results: list[EvaluationResult]) -> str:
        generated_at = datetime.now(timezone.utc).isoformat()
        lines = [
            "# Evaluation Report",
            "",
            f"- Generated by: {self.name}",
            f"- Generated at: {generated_at}",
            f"- Bugs evaluated: {len(results)}",
            "",
            "| Bug | Status | Started | Finished |",
            "| --- | --- | --- | --- |",
        ]
        for result in results:
            bug = result.bug
            label = f"{bug.benchmark}:{bug.project}:{bug.bug_id}"
            lines.append(
                f"| {label} | {result.status} | "
                f"{result.started_at.isoformat()} | {result.finished_at.isoformat()} |"
            )
        lines.append("")
        return "\n".join(lines)
